--- # Changes
---
--- - New in version 1.64
--- - Changed in version 1.94.0: Add NBT hash, item tags, lore, enchantment, and unbreakable flag.
--- - Changed in version 1.100.9: Add item groups.
--- - Changed in version 1.117.0: Add map color and potion effects.
