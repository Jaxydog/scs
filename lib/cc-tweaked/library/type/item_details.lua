--- Several functions in CC: Tweaked, such as `turtle.getItemDetail` and `inventory.getItemDetail`
--- provide a way to get information about an item stack.
---
--- This file details information about items that CC: Tweaked may return.
---
--- Some methods (such as `inventory.list` and `turtle.getItemDetail` without the detailed flag)
--- will only return the 'Basic information' about the item.
---
