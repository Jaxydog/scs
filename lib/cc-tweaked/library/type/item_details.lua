--- @class cc.ItemDetails
---
--- @field name string The namespaced ID for this item, e.g. `minecraft:dirt`.
---
--- See the Minecraft wiki for a list of vanilla item IDs.
---
--- @field count integer The number of items in the stack.
---
--- @field maxCount? integer The max possible size of the item stack.
---
--- @field nbt? string A hash of the NBT in the stack.
---
--- While this does not expose any information about the item's NBT,
--- it can be used as a way to compare items.
---
--- If two items have the same `name` and `nbt`,
--- then all other properties (e.g. durability, enchantment) will be the same.
---
--- @field displayName? string The translated display name of the item.
---
--- This uses the server's language.
---
--- This will typically be English on multiplayer servers, and your current language on single player.
---
--- @field lore? string[] Additional lore about this item, as a list of strings.
---
--- @field tags? table<string, boolean> The set of tags for this item.
---
--- This is a mapping of tag name to true.
---
--- While the representation of tags is a little more complicated than a single list,
--- this makes it very easy to check if an item has a certain tag:
---
--- ```lua
--- --- Check if the item in the turtle's inventory is a log.
--- local function is_log(slot)
---     local ok, block = turtle.getItemDetail(slot, true)
---    return ok and block.tags["minecraft:logs"]
--- end
--- ```
---
--- @field itemGroups? cc.ItemDetails.ItemGroup[] The item groups this item appears on.
---
--- Each item group is stored as a table, containing its id and display name.
---
--- > [!INFO]
--- > This information is not available on Minecraft 1.19.3 to 1.20.3.
--- > This field is present, but empty on those versions.
---
--- @field damage? integer The amount of damage this item has taken.
---
--- @field maxDamage? integer The maximum amount of damage this item has taken.
---
--- @field durability? number If this item is damaged (i.e. the durability bar is visible),
--- the percentage left on the durability bar, between 0 and 1 (inclusive).
---
--- @field unbreakable? boolean `true`, if the item is nubreakable
---
--- @field enchantments? cc.ItemDetails.Enchantment[] The enchantments this item has.
---
--- Each enchantment is a table containing several properties.
---
--- @field potionEffects? cc.ItemDetails.PotionEffect[] The effects this item has.
---
--- Each potion effect is a table containing several properties:
---
--- @field mapColor? integer The color of the block, as an RGB hex value.
---
--- The map color is just returned as a plain number (e.g. `9923917` for dirt).
--- It can either be displayed in hex with `string.format`,
--- or converted to individual RGB values with `colors.unpackRGB`.
---
--- @field mapColour? integer The colour of the block, as an RGB hex value.
---
--- The map colour is just returned as a plain number (e.g. `9923917` for dirt).
--- It can either be displayed in hex with `string.format`,
--- or converted to individual RGB values with `colours.unpackRGB`.

--- Data contained by an item group table.
---
--- @class cc.ItemDetails.ItemGroup
---
--- @field name string The namespaced ID for this item group, e.g. `minecraft:building_blocks`.
---
--- See the Minecraft wiki for a list of vanilla item group IDs.
---
--- @field displayName string The translated display name of the item group.
---
--- This uses the server's language.
---
--- This will typically be English on multiplayer servers, and your current language on single player.

--- Data contained by an enchantment table.
---
--- @class cc.ItemDetails.Enchantment
---
--- @field name string The namespaced ID for this enchantment, e.g. `minecraft:efficiency`.
---
--- See the Minecraft wiki for a list of vanilla enchantment IDs.
---
--- @field displayName string The translated display name of the enchantment.
---
--- This uses the server's language.
---
--- This will typically be English on multiplayer servers, and your current language on single player.
---
--- @field level integer The level for this enchantment.

--- Data contained by a potion effect table.
---
--- @class cc.ItemDetails.PotionEffect
---
--- @field name string The namespaced ID for this potion effect, e.g. `minecraft:regeneration`.
---
--- See the Minecraft wiki for a list of vanilla potion effect IDs.
---
--- @field displayName string The translated display name of the potion effect.
---
--- This uses the server's language.
---
--- This will typically be English on multiplayer servers, and your current language on single player.
---
--- @field duration? number The duration this effect will last for (if not instant), in seconds.
---
--- @field potency? integer The potency of this potion.
