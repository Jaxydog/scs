---
--- The `http_success` event is fired when an HTTP request returns successfully.
---
--- This event is normally handled inside `http.get` and `http.post`,
--- but it can still be seen when using `http.request`.
---
--- # Return values
---
--- 1. `string`: The event name.
--- 2. `string`: The URL of the site requested.
--- 3. `cc.http.Response`: The successful HTTP response.
---
--- # Usage
---
--- - Print the content of a website (this may fail if the request fails).
---
--- ```lua
--- local myUrl = 'https://tweaked.cc'
---
--- http.request(myUrl)
---
--- local event, url, handle
---
--- repeat
---     event, url, handle = os.pullEvent('http_success')
--- until url == myUrl
---
--- print('Contents of', url .. ':')
--- print(handle.readAll())
---
--- handle.close()
--- ```
---
