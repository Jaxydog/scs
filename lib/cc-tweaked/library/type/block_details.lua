--- # Examples
---
--- - A fully hydrated block of farmland.
---
--- ```lua
--- {
---     name = 'minecraft:farmland',
---     state = {
---         moisture = 7
---     },
---     tags = {
---         ['minecraft:mineable/shovel'] = true
---     },
---     mapColor = 9923917,
---     mapColour = 9923917,
--- }
--- ```
