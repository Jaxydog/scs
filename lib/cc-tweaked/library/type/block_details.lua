--- @class cc.BlockDetails
---
--- @field name string The namespaced ID for this block, e.g. `minecraft:dirt`.
---
--- See the Minecraft wiki for a list of vanilla block IDs.
---
--- @field state table<string, unknown> A table containing the block state of the block.
---
--- @field tags? table<string, boolean> The set of tags for this block.
---
--- This is a mapping of tag names to `true`.
---
--- While the representation of tags is a little more complicated than a single list,
--- this makes it very easy to check if a block has a certain tag:
---
--- ```lua
--- --- Check if the block in front of the turtle is a log.
--- local function is_log()
---     local ok, block = turtle.inspect()
---     return ok and block.tags["minecraft:logs"]
--- end
--- ```
---
--- @field mapColor? integer The color of the block, as an RGB hex value.
---
--- The map color is just returned as a plain number (e.g. `9923917` for farmland).
--- It can either be displayed in hex with `string.format`,
--- or converted to individual RGB values with `colors.unpackRGB`.
---
--- @field mapColour? integer The colour of the block, as an RGB hex value.
---
--- The map colour is just returned as a plain number (e.g. `9923917` for farmland).
--- It can either be displayed in hex with `string.format`,
--- or converted to individual RGB values with `colours.unpackRGB`.
