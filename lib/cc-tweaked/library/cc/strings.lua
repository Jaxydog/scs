--- [Official Documentation](https://tweaked.cc/library/cc.strings.html#v:wrap)
---
--- Wraps a block of text, so that each line fits within the given width.
---
--- This may be useful if you want to wrap text before displaying it to a `monitor` or `printer` without using `print`.
---
--- # Usage
---
--- - Wrap a string and write it to the terminal.
---
--- ```lua
--- term.clear()
---
--- local lines = require('cc.strings').wrap('This is a long piece of text', 10)
---
--- for i = 1, #lines do
---     term.setCursorPos(1, i)
---     term.write(lines[i])
--- end
--- ```
---
--- @param text string The string to wrap.
--- @param width? integer The width to constrain to, defaults to the width of the terminal.
---
--- @return string[] wrapped The wrapped input string as a list of lines.
function strings.wrap(text, width) end

--- [Official Documentation](https://tweaked.cc/library/cc.strings.html#v:ensure_width)
---
--- Makes the input string a fixed width. This either truncates it, or pads it with spaces.
---
--- # Usage
---
--- - Extend a string.
---
--- ```lua
--- require('cc.strings').ensure_width('a short string', 20)
--- ```
---
--- - Truncate a string.
---
--- ```lua
--- require('cc.strings').ensure_width('a rather long string which is truncated', 20)
--- ```
---
--- @param line string The string to normalize.
--- @param width? integer The width to constrain to, defaults to the width of the terminal.
---
--- @return string normalized The string with a specific width.
function strings.ensure_width(line, width) end

--- [Official Documentation](https://tweaked.cc/library/cc.strings.html#v:split)
---
--- Split a string into parts, each separated by a deliminator.
---
--- For instance, splitting the string `'a b c'` with the deliminator `' '`, would return a table with
--- three strings: `'a'`, `'b'`, and `'c'`.
---
--- By default, the deliminator is given as a Lua pattern. Passing `true` to the `plain` argument will cause the
--- deliminator to be treated as a literal string.
---
--- # Usage
---
--- - Split a string into words.
---
--- ```lua
--- require('cc.strings').split('This is a sentence.', '%s+')
--- ```
---
--- - Split a string by `'-'` into at most 3 elements.
---
--- ```lua
--- require('cc.strings').split('a-separated-string-of-sorts', '-', true, 3)
--- ```
---
--- # Changes
---
--- - New in version 1.112.0
---
--- @param str string The string to split.
--- @param delimiter string The pattern to split this string on.
--- @param plain? boolean Treat the deliminator as a plain string, rather than a pattern (default `false`).
--- @param limit? integer The maximum number of elements in the returned list.
---
--- @return string[] list The list of split strings.
function strings.split(str, delimiter, plain, limit) end

