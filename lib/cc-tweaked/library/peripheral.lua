--- [Official Documentation](https://tweaked.cc/module/peripheral.html#v:wrap)
---
--- Get a table containing all functions available on a peripheral.
--- These can then be called instead of using `peripheral.call` every time.
---
--- # Usage
---
--- - Open the modem on top of the computer.
---
--- ```lua
--- local modem = peripheral.wrap('top')
---
--- modem.open(1)
--- ```
---
--- @param name cc.peripheral.Name The name of the peripheral to wrap.
---
--- @return cc.peripheral.Peripheral? peripheral The table containing the peripheral's methods,
--- or `nil` if there is no peripheral present with the given name.
function peripheral.wrap(name) end

--- [Official Documentation](https://tweaked.cc/module/peripheral.html#v:find)
---
--- Find all peripherals of a specific type, and return the wrapped peripherals.
---
--- # Usage
---
--- - Find all monitors and store them in a table, writing 'Hello' on each one.
---
--- ```lua
--- local monitors = { peripheral.find('monitor') }
---
--- for _, monitor in ipairs(monitors) do
---     monitor.write('Hello')
--- end
--- ```
---
--- - Find all wireless modems connected to this computer.
---
--- ```lua
--- local modems = {
---     peripheral.find('modem', function(name, modem)
---         return modem.isWireless()
---     end)
--- }
--- ```
---
--- - This abuses the `filter` argument to call `rednet.open` on every modem.
---
--- ```lua
--- peripheral.find('modem', rednet.open)
--- ```
---
--- # Changes
---
--- - New in version 1.6
---
--- @param peripheralType string The type of peripheral to look for.
--- @param filter? fun(name: cc.peripheral.Name, wrapped: cc.peripheral.Peripheral): boolean A filter function,
--- which takes the peripheral's name and wrapped table and returns if it should be included in the result.
---
--- @return cc.peripheral.Peripheral... wrapped Zero or more wrapped peripherals matching the given filters.
function peripheral.find(peripheralType, filter) end
