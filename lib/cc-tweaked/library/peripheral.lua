--- [Official Documentation](https://tweaked.cc/module/peripheral.html#v:isPresent)
---
--- Determines if a peripheral is present with the given name.
---
--- # Usage
---
--- - Check for a peripheral attached to the top of the computer.
---
--- ```lua
--- peripheral.isPresent('top')
--- ```
---
--- - Check for a networked `monitor_0` peripheral.
---
--- ```lua
--- peripheral.isPresent('monitor_0')
--- ```
---
--- @param name cc.peripheral.Name The side or network name that you want to check.
---
--- @return boolean result If a peripheral is present with the given name.
function peripheral.isPresent(name) end

