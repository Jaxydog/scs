--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:send)
---
--- Allows a computer or turtle with an attached modem to send a message intended for a computer with a specific ID.
--- At least one such modem must first be opened before sending is possible.
---
--- Assuming the target was in range and had a correctly opened modem, the target computer may then
--- use `rednet.receive` to collect the message.
---
--- # Usage
---
--- - Send a message to computer #2.
---
--- ```lua
--- rednet.send(2, 'Hello from rednet!')
--- ```
---
--- # Changes
---
--- - Changed in version 1.6: Added protocol parameter.
--- - Changed in version 1.82.0: Now returns whether the message was successfully sent.
---
--- @param recipient integer The ID of the receiving computer.
--- @param message any The message to send. Like with `modem.transmit`, this can contain any primitive type as well
--- as tables. Other types (like functions), as well as metatables, will not be transmitted.
--- @param protocol? string The 'protocol' to send this message under. When using `rednet.receive`, one can filter to
--- only receive messages sent under a particular protocol.
---
--- @return boolean sent If this message was successfully sent (i.e., if rednet is currently open).
--- Note, this does not guarantee the message was actually received.
---
--- @see rednet.receive()
function rednet.send(recipient, message, protocol) end

--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:broadcast)
---
--- Broadcasts a string message over the predefined `CHANNEL_BROADCAST` channel.
--- The message will be received by every device listening to rednet.
---
--- # Usage
---
--- - Broadcasts the words 'Hello, world!' to every rednet computer.
---
--- ```lua
--- rednet.broadcast('Hello, world!')
--- ```
---
--- # Changes
---
--- - Changed in version 1.6: Added protocol parameter.
---
--- @param message any The message to send. This should not contain coroutines or functions, as they will be
--- converted to nil.
--- @param protocol? string The 'protocol' to send this message under. When using `rednet.receive` one can filter to
--- only receive messages sent under a particular protocol.
---
--- @see rednet.receive()
function rednet.broadcast(message, protocol) end

--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:receive)
---
--- Wait for a rednet message to be received, or until timeout seconds have elapsed.
---
--- # Usage
---
--- - Receive a rednet message.
---
--- ```lua
--- local id, message = rednet.receive()
---
--- print(('Computer %d sent message %s'):format(id, message))
--- ```
---
--- - Receive a message, stopping after 5 seconds if no message was received.
---
--- ```lua
--- local id, message = rednet.receive(nil, 5)
---
--- if not id then
---     printError("No message received")
--- else
---     print(('Computer %d sent message %s'):format(id, message))
--- end
--- ```
---
--- - Receive a message from computer #2.
---
--- ```lua
--- local id, message
--- repeat
---     id, message = rednet.receive()
--- until id == 2
---
--- print(message)
--- ```
---
--- # Changes
---
--- - Changed in version 1.6: Added protocol parameter.
---
--- @param protocolFilter? string The protocol the received message must be sent with. If specified, any messages not
--- sent under this protocol will be discarded.
--- @param timeout? number The number of seconds to wait if no message is received.
---
--- @return integer? id The computer which sent this message.
--- @return any message The received message.
--- @return string? protocol The protocol this message was sent under.
---
--- @return_overload integer, any, string?
--- @return_overload nil
---
--- @see rednet.broadcast()
--- @see rednet.send()
function rednet.receive(protocolFilter, timeout) end

--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:host)
---
--- Register the system as 'hosting' the desired protocol under the specified name.
--- If a rednet lookup is performed for that protocol (and maybe name) on the same network, the registered system will
--- automatically respond via a background process, hence providing the system performing the lookup with its ID number.
---
--- Multiple computers may not register themselves on the same network as having the same names against the same
--- protocols, and the title `localhost` is specifically reserved. They may, however, share names as long as their
--- hosted protocols are different, or if they only join a given network after 'registering' themselves before
--- doing so (e.g., while offline or part of a different network).
---
--- # Throws
---
--- - If trying to register a hostname which is reserved, or currently in use.
---
--- # Changes
---
--- - New in version 1.6
---
--- @param protocol string The protocol this computer provides.
--- @param hostname string The name this computer exposes for the given protocol.
---
--- @see rednet.lookup()
--- @see rednet.unhost()
function rednet.host(protocol, hostname) end

