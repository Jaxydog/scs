--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:open)
---
--- Opens a modem with the given `peripheral` name, allowing it to send and receive messages over rednet.
---
--- This will open the modem on two channels: one which has the same ID as the computer, and another on the
--- broadcast channel.
---
--- # Throws
---
--- - If there is no such modem with the given name.
---
--- # Usage
---
--- - Open rednet on the back of the computer.
---
--- ```lua
--- rednet.open('back')
--- ```
---
--- - Open rednet on all attached modems.
---
--- ```lua
--- peripheral.find('modem', rednet.open)
--- ```
---
--- @param modem string The name of the modem to open.
---
--- @see rednet.isOpen()
--- @see rednet.close()
function rednet.open(modem) end

--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:close)
---
--- Close a modem with the given `peripheral` name, meaning it can no longer send and receive rednet messages.
---
--- # Throws
---
--- - If there is no such modem with the given name.
---
--- @param modem? string The side the modem exists on. If not given, all open modems will be closed.
---
--- @see rednet.open()
function rednet.close(modem) end

