--- [Official Documentation](https://tweaked.cc/module/rednet.html)
---
--- Communicate with other computers by using modems.
--- `rednet` provides a layer of abstraction on top of the main modem peripheral, making it slightly easier to use.
---
--- ## Basic usage
---
--- In order to send a message between two computers, each computer must have a modem on one of its sides
--- (or in the case of pocket computers and turtles, the modem must be equipped as an upgrade).
--- The two computers should then call `rednet.open`, which sets up the modems ready to send and receive messages.
---
--- Once rednet is opened, you can send messages using `rednet.send` and receive them using `rednet.receive`.
--- It's also possible to send a message to every rednet-using computer using `rednet.broadcast`.
---
--- > [!WARNING]
--- > While rednet provides a friendly way to send messages to specific computers, it doesn't provide any guarantees
--- > about security. Other computers could be listening in to your messages, or even pretending to send messages from
--- > other computers!
--- >
--- > If you're playing on a multiplayer server (or at least one where you don't trust other players), it's worth
--- > encrypting or signing your rednet messages.
---
--- ## Protocols and hostnames
---
--- Several rednet messages accept 'protocol's - simple string names describing what a message is about. When sending
--- messages using `rednet.send` and `rednet.broadcast`, you can optionally specify a protocol for the message.
--- This same protocol can then be given to `rednet.receive`, to ignore all messages not using this protocol.
---
--- It's also possible to look-up computers based on protocols, providing a basic system for service discovery and DNS.
--- A computer can advertise that it supports a particular protocol with `rednet.host`, also providing a friendly
--- 'hostname'. Other computers may then find all computers which support this protocol using `rednet.lookup`.
---
