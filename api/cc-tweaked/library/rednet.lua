--- @param protocol string The protocol to unregister yourself from.
function rednet.unhost(protocol) end

--- [Official Documentation](https://tweaked.cc/module/rednet.html#v:lookup)
---
--- Search the local rednet network for systems hosting the desired protocol and returns any computer IDs that
--- respond as 'registered' against it.
---
--- If a hostname is specified, only one ID will be returned (assuming an exact match is found).
---
--- # Usage
---
--- - Find all computers which are hosting the `'chat'` protocol.
---
--- ```lua
--- local computers = { rednet.lookup('chat') }
---
--- print(('%d computers available to chat'):format(#computers))
---
--- for _, computer in pairs(computers) do
---     print(('Computer #%d'):format(computer))
--- end
--- ```
---
--- - Find a computer hosting the `'chat'` protocol with a hostname of `'my_host'`.
---
--- ```lua
--- local id = rednet.lookup('chat', 'my_host')
---
--- if id then
---     print(('Found my_host at computer #%d'):format(id))
--- else
---     printError('Cannot find my_host')
--- end
--- ```
---
--- # Changes
---
--- - New in version 1.6
--- - Changed in version 1.118.0: Added `timeout` parameter.
---
--- @param protocol string The protocol to search for.
--- @param hostname? string The hostname to search for.
--- @param timeout? number The number of seconds to wait for a lookup response (default `2`).
--- @return integer... id A list of computer IDs hosting the given protocol, or, if `hostname` is specified,
--- the computer ID with the provided hostname and protocol, or `nil` if none exists.
function rednet.lookup(protocol, hostname, timeout) end

