--- The `file_transfer` event is queued when a user drags-and-drops a file on an open computer.
---
--- This event contains a single argument of type `TransferredFiles`, which can be used to get the files
--- to be transferred. Each file returned is a binary file handle with an additional `getName` method.
---
--- # Return values
---
--- 1. `string`: The event name.
--- 2. `cc.os.Event.FileTransfer.TransferredFiles`: The list of transferred files.
---
--- # Usage
---
--- - Wait for a user to drop files on top of the computer, then print the list of files and the size of each file.
---
--- ```lua
--- local _, files = os.pullEvent('file_transfer')
---
--- for _, file in ipairs(files.getFiles()) do
---     local size = file.seek('end')
---     file.seek('set', 0)
---
---     print(file.getName(), size)
--- end
--- ```
---
--- - Save each transferred file to the computer's storage.
---
--- ```lua
--- local _, files = os.pullEvent('file_transfer')
---
--- for _, file in ipairs(files.getFiles()) do
---     local handle = fs.open(file.getName(), 'wb')
---     handle.write(file.readAll())
---
---     handle.close()
---     file.close()
--- end
--- ```
